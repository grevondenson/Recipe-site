export function findCuratedRecipes(query: string): RecipeSearchResult[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];

  const tokens = q.split(/\s+/).filter(Boolean);

  const matched = CURATED_RECIPES.filter((recipe) => {
    const haystack = `${recipe.title} ${recipe.summary} ${recipe.cuisines.join(" ")} ${recipe.dishTypes.join(" ")}`.toLowerCase();
    return tokens.some((token) => haystack.includes(token));
  });

  return matched.map((recipe) => ({
    id: recipe.id,
    title: recipe.title,
    image: recipe.image,
    readyInMinutes: recipe.readyInMinutes,
    servings: recipe.servings,
    cuisines: recipe.cuisines,
    dishTypes: recipe.dishTypes,
    diets: recipe.diets,
  }));
}

export function getCuratedRecipeById(id: number): Recipe | null {
  return CURATED_RECIPES.find((r) => r.id === id) ?? null;
}
